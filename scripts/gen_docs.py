def variant_page(model, info, aliases, defs):
    pack = defs[model]
    tokens = pack["tokens"]["tokens"]
    fields = pack["fields"]
    mi = info[model]
    family = {"nd10": "NORD-10", "nd1x0": "ND-100, ND-110 and ND-120", "nd5xx": "ND-500 and ND-5000"}[mi["family"]]
    spelling = ", ".join(code(a) for a in aliases.get(model, []) if a != model) or "none"
    yaml_name = "defs/tokens/%s-tokens.yaml" % model
    order, groups = categories_in_order(tokens)
    wide = "parts" in tokens[0]["encoding"]

    out = [BANNER, "# %s\n\n" % mi["display"], esc(mi["description"]) + "\n\n"]
    out.append(kv_table([
        ["Name for `%#MODEL` and the settings", code(model)],
        ["Also accepted", spelling],
        ["Word width in the bit view", "%d bits" % mi["wordBits"]],
        ["Image written by *Assemble*", esc(mi["nativeFormat"])],
        ["Ending of the image file", code(mi["outputExtension"])],
        ["Mnemonics", str(len(tokens))],
        ["Colours shared with", esc(family)],
        ["Definitions", "[`%s`](%s/%s)" % (yaml_name, META_URL, yaml_name)],
    ]))

    out.append("\n## How the bits are given\n\n")
    if wide:
        n = len(tokens[0]["encoding"]["parts"])
        out.append("The word is %d groups of 16 bits. Each group is written as 6 octal digits, "
                   "most significant group first. Groups that are all zero are left out of the tables below. "
                   "A mnemonic sets the bits that are 1 in its groups; the mnemonics of one instruction "
                   "are ORed together.\n\n" % n)
    else:
        out.append("The word is four groups of 16 bits: `w4` (bits 63-48), `w3` (47-32), `w2` (31-16) and "
                   "`w1` (15-0), each written as 6 octal digits. Groups that are all zero are left out of the "
                   "tables below. A mnemonic sets the bits that are 1 in its groups; the mnemonics of one "
                   "instruction are ORed together.\n\n")

    fs = fields_section(model, fields)
    if fs:
        out.append("## Fields of the word\n\n")
        if fields.get("inherits_from"):
            out.append("The fields below are the ones this variant defines itself. The other fields are "
                       "those of `%s`; see the page of that variant.\n\n" % fields["inherits_from"])
        if "control_store_words" in fields:
            csw = fields["control_store_words"]
            out.append("`control_store_words` in the definitions: %s.\n\n" % (", ".join(str(x) for x in csw) if isinstance(csw, list) else csw))
        out.append(fs)
        out.append(lines_section(fields))
        out.append(rom_notes(fields))

    out.append("\n## Mnemonics\n\n")
    out.append("%d mnemonics in %d categories.\n\n" % (len(tokens), len(order)))
    out.append(table(["Category", "Mnemonics"],
                     [["[%s](#%s)" % (c, c.lower()), str(len(groups[c]))] for c in order],
                     ["---", "---:"]))
    for c in order:
        out.append("\n### %s\n\n" % c)
        rows = [[code(t["token"]), bit_lines(t), esc(t.get("description", "")), notes(t)]
                for t in groups[c]]
        out.append(table(["Mnemonic", "Bits", "Description", "Notes"], rows))
    return "".join(out)


def dly_page(info, aliases, defs):
    mi = info["nd120-dly"]
    nd120 = defs["nd120"]["tokens"]
    base = {t["token"]: t for t in nd120["tokens"]}
    overrides = nd120["variant_overrides"]["nd120-dly"]
    spelling = ", ".join(code(a) for a in aliases.get("nd120-dly", []) if a != "nd120-dly")
    out = [BANNER, "# %s\n\n" % mi["display"], esc(mi["description"]) + "\n\n"]
    out.append(kv_table([
        ["Name for `%#MODEL` and the settings", code("nd120-dly")],
        ["Also accepted", spelling],
        ["Word width in the bit view", "%d bits" % mi["wordBits"]],
        ["Image written by *Assemble*", esc(mi["nativeFormat"])],
        ["Ending of the image file", code(mi["outputExtension"])],
        ["Mnemonics", str(len(nd120["tokens"]))],
        ["Definitions", "[`defs/tokens/nd120-tokens.yaml`, block `variant_overrides`](%s/defs/tokens/nd120-tokens.yaml)" % META_URL],
    ]).replace("|  |  |\n| --- | --- |\n", "| | |\n|---|---|\n"))
    out.append("\nThis variant is the [ND-120](nd120.md) table for version L microcode. It has the same "
               "mnemonics, the same fields and the same bits, except for %d mnemonics: the register selects "
               "that are assembled without the DLY1 bit (bit 27).\n\n" % len(overrides))
    out.append("## Mnemonics that differ from the ND-120\n\n")
    rows = []
    for o in overrides:
        b = base[o["token"]]
        rows.append([code(o["token"]), bit_lines(b), bit_lines(o), esc(o.get("description", ""))])
    out.append(table(["Mnemonic", "ND-120 (version K)", "ND-120 (version L)", "Description (version L)"], rows))
    out.append("\nAll other mnemonics are listed on the [ND-120](nd120.md#mnemonics) page.\n")
    return "".join(out)


def index_page(models, info, defs):
    out = [BANNER, "# Variants\n\n",
           "The extension knows seven variant names. The page of each one lists its fields and "
           "every mnemonic with its bits. The data comes from the YAML definitions of "
           "[nd-microcode-meta](https://github.com/RetroCoreLabs/nd-microcode-meta); see "
           "[Choosing the variant](../choosing-the-variant.md) for how a file gets its variant.\n\n"]
    rows = []
    for m in models:
        mi = info[m]
        count = len(defs["nd120" if m == "nd120-dly" else m]["tokens"]["tokens"])
        rows.append(["[%s](%s.md)" % (esc(mi["display"]), m), code(m), "%d" % mi["wordBits"], str(count),
                     esc(mi["nativeFormat"]), code(mi["outputExtension"])])
    out.append(table(["Variant", "Name", "Word bits", "Mnemonics", "Image written by *Assemble*", "Ending"], rows,
                     ["---", "---", "---:", "---:", "---", "---"]))
    out.append("\n`nd120-dly` has the mnemonics of `nd120`; the count is the same.\n")
    return "".join(out)


# ---------------------------------------------------------------------------
# Navigation
# ---------------------------------------------------------------------------

def tracked(rel):
    """True when git knows the file (tracked, or new and not ignored)."""
    try:
        out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard", "--", rel],
                             cwd=ROOT, capture_output=True, text=True, check=True).stdout
        return rel in out.split("\n")
    except (OSError, subprocess.CalledProcessError):
        return os.path.exists(os.path.join(ROOT, rel))


def page_title(rel):
    for line in read(rel).split("\n"):
        if line.startswith("# "):
            return line[2:].strip()
    return os.path.basename(rel)


def nav(models, info):
    items = [{"Home": "README.md"}]
    for g in GUIDES:
        if tracked(g):
            items.append({page_title(g): g})
    items.append({"Variants": [{"Overview": "docs/variants/index.md"}] +
                  [{info[m]["display"]: "docs/variants/%s.md" % m} for m in models]})
    others = sorted(f for f in os.listdir(os.path.join(ROOT, "docs"))
                    if f.endswith(".md") and "docs/" + f not in GUIDES and tracked("docs/" + f))
    for f in others:
        items.append({page_title("docs/" + f): "docs/" + f})
    if tracked("CHANGELOG.md"):
        items.append({"Changelog": "CHANGELOG.md"})
    return items


# ---------------------------------------------------------------------------

def main():
    check = "--check" in sys.argv[1:]
    models = read_all_models()
    aliases = read_aliases()
    info = read_model_info()
    defs = json.loads(read("src/generated/definitions.json"))
    for m in models:
        if m not in info:
            raise SystemExit("models.ts has no entry for " + m)

    files = {}
    for m in models:
        if m == "nd120-dly":
            files["docs/variants/nd120-dly.md"] = dly_page(info, aliases, defs)
        else:
            files["docs/variants/%s.md" % m] = variant_page(m, info, aliases, defs)
    files["docs/variants/index.md"] = index_page(models, info, defs)

    header = ("# Made by scripts/gen_docs.py. Do not edit; change docs-site/base.yml or the script.\n"
              "# Navigation of the documentation site.\nINHERIT: base.yml\n\n")
    files["docs-site/mkdocs.yml"] = header + yaml.safe_dump({"nav": nav(models, info)},
                                                           sort_keys=False, allow_unicode=False,
                                                           default_flow_style=False, width=1000)

    changed = []
    for rel, text in files.items():
        path = os.path.join(ROOT, rel)
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8", newline="") as f:
                old = f.read()
        if old != text:
            changed.append(rel)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    if check:
        for rel in changed:
            print("out of date:", rel, file=sys.stderr)
        if changed:
            print("run: python3 scripts/gen_docs.py", file=sys.stderr)
            return 1
        print("generated pages are up to date (%d files)" % len(files))
        return 0
    print("wrote %d files, %d changed" % (len(files), len(changed)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
