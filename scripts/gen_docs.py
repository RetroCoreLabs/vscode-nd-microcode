#!/usr/bin/env python3
"""Make the generated part of the documentation site.

Writes:
  docs/variants/index.md       the seven variants side by side
  docs/variants/<name>.md      one page per variant: fields and every mnemonic
  docs-site/mkdocs.yml         the navigation (inherits docs-site/base.yml)

The facts come from files that are in the repository, never typed in here:
  src/generated/definitions.json   tokens and fields of every variant (snapshot of the YAML)
  src/core/models.ts               display name, word width, output format per variant
  external/meta/lib/ts/src/types.ts  the list of variants and the accepted spellings

Run from anywhere:
  python3 scripts/gen_docs.py            write the files
  python3 scripts/gen_docs.py --check    write nothing; exit 1 if a file would change

The hand-written pages (README.md, CHANGELOG.md, docs/*.md) are not touched.
"""

import json
import os
import re
import subprocess
import sys

import yaml

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
META_URL = "https://github.com/RetroCoreLabs/nd-microcode-meta/blob/main"
BANNER = "<!-- generated by scripts/gen_docs.py; edit the YAML in nd-microcode-meta or the script, then regenerate -->\n\n"

# Order of the hand-written pages in the navigation. Pages in docs/ that are
# not listed here are added after these, in name order.
GUIDES = [
    "docs/getting-started.md",
    "docs/choosing-the-variant.md",
    "docs/commands.md",
    "docs/settings.md",
    "docs/hover-and-colours.md",
    "docs/source-forms.md",
]


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


# ---------------------------------------------------------------------------
# Facts from the TypeScript files
# ---------------------------------------------------------------------------

def ts_string(text):
    return json.loads(text)


def read_all_models():
    src = read("external/meta/lib/ts/src/types.ts")
    m = re.search(r"ALL_MODELS[^=]*=\s*\[(.*?)\]", src, re.S)
    if not m:
        raise SystemExit("types.ts: ALL_MODELS not found")
    return re.findall(r'"([a-z0-9-]+)"', m.group(1))


def read_aliases():
    src = read("external/meta/lib/ts/src/types.ts")
    m = re.search(r"MODEL_ALIASES[^=]*=\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("types.ts: MODEL_ALIASES not found")
    out = {}
    for key, value in re.findall(r'"?([a-z0-9-]+)"?\s*:\s*"([a-z0-9-]+)"', m.group(1)):
        out.setdefault(value, []).append(key)
    return out


def read_model_info():
    src = read("src/core/models.ts")
    m = re.search(r"MODEL_INFO[^=]*=\s*\{(.*?)\n\};", src, re.S)
    if not m:
        raise SystemExit("models.ts: MODEL_INFO not found")
    info = {}
    for name, body in re.findall(r'\n  "?([a-z0-9-]+)"?: \{(.*?)\n  \},', m.group(1), re.S):
        entry = {}
        for key, value in re.findall(r'(\w+):\s*("(?:[^"\\]|\\.)*"|\d+)', body):
            entry[key] = ts_string(value) if value.startswith('"') else int(value)
        info[name] = entry
    return info


# ---------------------------------------------------------------------------
# Text helpers
# ---------------------------------------------------------------------------

def esc(text):
    """Escape text for a Markdown table cell."""
    text = " ".join(str(text).split())
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    for ch in "\\`*_[]{}|":
        text = text.replace(ch, "\\" + ch)
    return text


def code(text):
    text = str(text)
    if "`" in text or "|" in text or "\n" in text:
        raise SystemExit("token or value with a backtick, bar or newline: " + repr(text))
    return "`" + text + "`"


def bits(hi, lo):
    return str(hi) if hi == lo else "%d:%d" % (hi, lo)


def kv_table(rows):
    """Facts as a bullet list (a table without a header looks wrong)."""
    return "\n".join("- **%s:** %s" % (key, value) for key, value in rows) + "\n"


def table(header, rows, align=None):
    align = align or ["---"] * len(header)
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join(align) + " |"]
    for row in rows:
        out.append("| " + " | ".join(row) + " |")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------
# Token and field rendering
# ---------------------------------------------------------------------------

def bit_lines(token):
    """The non-zero 16-bit groups of the encoding, one per line."""
    enc = token["encoding"]
    lines = []
    if "parts" in enc:
        n = len(enc["parts"])
        top = n * 16 - 1
        for i, part in enumerate(enc["parts"]):
            if int(part, 8) != 0:
                hi = top - 16 * i
                lines.append("%s %s" % (code(part), "(bits %d-%d)" % (hi, hi - 15)))
    else:
        ranges = {"w4": "63-48", "w3": "47-32", "w2": "31-16", "w1": "15-0"}
        for w in ("w4", "w3", "w2", "w1"):
            if int(enc[w], 8) != 0:
                lines.append("%s %s" % (code(enc[w]), "(%s, bits %s)" % (w, ranges[w])))
    return "<br>".join(lines) if lines else "all zero"


def notes(token):
    out = []
    if token.get("display_line"):
        out.append("line %s" % token["display_line"])
    if token.get("nd120_only"):
        out.append("ND-120 only")
    if token.get("provides"):
        out.append("provides " + str(token["provides"]))
    if token.get("requires"):
        out.append("requires " + str(token["requires"]))
    if token.get("field") is not None:
        out.append("%s = %s" % (token["field"], token.get("value")))
    if token.get("mem_code") is not None:
        out.append("memory code %s" % token["mem_code"])
    if token.get("alias_of"):
        out.append("same as " + str(token["alias_of"]))
    if token.get("alias_on_manual"):
        out.append("manual name " + str(token["alias_on_manual"]))
    return esc(", ".join(out))


def categories_in_order(tokens):
    order, groups = [], {}
    for t in tokens:
        c = t["category"]
        if c not in groups:
            groups[c] = []
            order.append(c)
        groups[c].append(t)
    return order, groups


def fields_section(model, fields):
    """Markdown for the field layout of a variant, or '' when there is none."""
    out = []
    if "fields" in fields and isinstance(fields["fields"], dict):
        rows = []
        for name, f in fields["fields"].items():
            hi, lo = f["bits"]
            rows.append([code(name), bits(hi, lo), str(f.get("width", hi - lo + 1)),
                         esc(f.get("description", "")), esc(f.get("used_when", "")),
                         esc(f.get("default", "")) if "default" in f else ""])
        out.append(table(["Field", "Bits", "Width", "Description", "Used when", "Default"], rows,
                         ["---", "---:", "---:", "---", "---", "---"]))
    elif "fields" in fields and isinstance(fields["fields"], list):
        rows = [[code(f["name"]), bits(f["high_bit"], f["low_bit"]), esc(f.get("format", ""))]
                for f in fields["fields"]]
        out.append(table(["Field", "Bits", "Format"], rows, ["---", "---:", "---"]))
    if "partition" in fields:
        rows = [[code(f["name"]), bits(f["high_bit"], f["low_bit"]), esc(f.get("description", ""))]
                for f in fields["partition"]]
        out.append(table(["Field", "Bits", "Description"], rows, ["---", "---:", "---"]))
    if "subfields" in fields:
        rows = [[code(f["name"]), bits(f["high_bit"], f["low_bit"]), esc(f.get("description", ""))]
                for f in fields["subfields"]]
        out.append("\n### Sub-fields\n\nParts of the fields above that the assembler fills separately.\n\n")
        out.append(table(["Sub-field", "Bits", "Description"], rows, ["---", "---:", "---"]))
    return "".join(out)


def lines_section(fields):
    cats = fields.get("categories")
    if not cats:
        return ""
    rows = [[esc(c.get("name", key)), esc(c.get("description", "")),
             ", ".join(code(f) for f in c.get("fields", []))] for key, c in cats.items()]
    return "\n### Fields by line of the instruction\n\n" + table(["Line", "Content", "Fields"], rows)


def rom_notes(fields):
    """The keys of the definitions that describe the ROM form of the words, as tables."""
    out = ""
    for key in ("rom_bit_inversion", "rom_bit_flip"):
        if key not in fields:
            continue
        rows = []
        for k, v in fields[key].items():
            if isinstance(v, list):
                v = ", ".join(str(x) for x in v)
            rows.append([code(k), esc(v)])
        title = {"rom_bit_inversion": "ROM bit inversion", "rom_bit_flip": "ROM bit flip"}[key]
        out += "\n### %s\n\nFrom the definitions, key `%s`.\n\n" % (title, key)
        out += table(["Key", "Value"], rows)
    return out


